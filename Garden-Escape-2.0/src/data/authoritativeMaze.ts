// Direction utilities
// 0 = North (dy: -1), 1 = East (dx: +1), 2 = South (dy: +1), 3 = West (dx: -1)
export const DIRS = [
  { dx: 0, dy: -1 }, // 0: North
  { dx: 1, dy: 0 },  // 1: East
  { dx: 0, dy: 1 },  // 2: South
  { dx: -1, dy: 0 }  // 3: West
];

export const RELATIVE_OFFSETS = {
  FORWARD: 0,
  RIGHT: 1,
  BACKWARD: 2,
  LEFT: 3
} as const;

export type RelativeDirection = keyof typeof RELATIVE_OFFSETS;

export function getAbsoluteDirection(currentOrientation: number, relative: RelativeDirection): number {
  return (currentOrientation + RELATIVE_OFFSETS[relative]) % 4;
}

export function isTraversable(
  grid: number[][],
  x: number,
  y: number,
  unlockedGates: string[] = [],
  gates: GateDef[] = []
): boolean {
  if (x < 0 || y < 0 || y >= grid.length || x >= grid[0].length) return false;
  if (grid[y][x] === 1) return false; // Wall

  // Check if locked gate exists on this cell
  const gateAtCell = gates.find(g => g.x === x && g.y === y);
  if (gateAtCell && !unlockedGates.includes(gateAtCell.id)) {
    return false; // Locked gate
  }

  return true;
}

export function getValidRelativeDirections(
  grid: number[][],
  currentX: number,
  currentY: number,
  currentOrientation: number,
  unlockedGates: string[] = [],
  gates: GateDef[] = [],
  availableKeys = 0
): RelativeDirection[] {
  const valid: RelativeDirection[] = [];
  const rels: RelativeDirection[] = ['FORWARD', 'LEFT', 'RIGHT', 'BACKWARD'];

  for (const rel of rels) {
    const absDir = getAbsoluteDirection(currentOrientation, rel);
    const targetX = currentX + DIRS[absDir].dx;
    const targetY = currentY + DIRS[absDir].dy;

    const gate = gates.find((g) => g.x === targetX && g.y === targetY);
    const effectiveUnlockedGates = gate && availableKeys >= gate.requiredKeys
      ? [...unlockedGates, gate.id]
      : unlockedGates;
    if (isTraversable(grid, targetX, targetY, effectiveUnlockedGates, gates)) {
      valid.push(rel);
    }
  }

  return valid;
}
